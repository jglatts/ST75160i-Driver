/***********************************************************/
void I2C_Start()       //I2C Start condition
{
    digitalWrite(SCL, HIGH);
    digitalWrite(SDA, HIGH);
    digitalWrite(SDA, LOW);
    digitalWrite(SCL, LOW);
}

/***********************************************************/
void I2C_Stop()       //I2C Stop Condition
{
    digitalWrite(SDA, LOW);
    digitalWrite(SCL, LOW);
    digitalWrite(SCL, HIGH);
    digitalWrite(SDA, HIGH);
}

/***********************************************************/
//Function Used to send Command/Data to display
void I2C_Out(unsigned char c) {       

    for (int i = 0; i < 8; i++) {

        if ((c & 0x80) == 0x80) {
            digitalWrite(SDA, HIGH);
        }
        else {
            digitalWrite(SDA, LOW);
        }
        c = (c << 1);
        digitalWrite(SCL, LOW);
        digitalWrite(SCL, HIGH);
        digitalWrite(SCL, LOW);
    }
    digitalWrite(SCL, HIGH);
    while (SDA == 1) {
        digitalWrite(SCL, LOW);
        digitalWrite(SCL, HIGH);
    }
    digitalWrite(SCL, LOW);

}

/***********************************************************/
void command(unsigned char c)       //Function used to send Commands 
{
    I2C_Stop();
    I2C_Start();
    I2C_Out(slave);
    I2C_Out(comm);
    I2C_Out(c);
}

/***********************************************************/
void data(unsigned char d)          //Function used to send image Data
{
    I2C_Stop();
    I2C_Start();
    I2C_Out(slave);
    I2C_Out(dat);
    I2C_Out(d);
}
/***********************************************************/
void Write_enable()                 //Sets writing address and allows you to begin sending image data
{
    command(0x75);
    data(0x00);
    data(0x18);
    command(0x5C);
}
/***********************************************************/
void ImageDisplay(const unsigned char* image)
{
    Write_enable();
    unsigned int i, j;
    for (i = 0; i < 12; i++) {

        for (j = 0; j < 160; j++) {  //128 columns wide
            data(*image);           //send picture data
            image++;
        }
    }
}

/***********************************************************/
//Initialize pins used 
void setpins()           
{
    pinMode(RST, OUTPUT);
    pinMode(SCL, OUTPUT);
    pinMode(SDA, OUTPUT);
    digitalWrite(SDA, HIGH);
    digitalWrite(SCL, HIGH);
    digitalWrite(RST, HIGH);
}

/***********************************************************/
//This function fills the screen with the data value passed in
void fill_screen(unsigned char d)     
{
    Write_enable();
    for (int x = 0; x < 25; x++) {
        for (int n = 0; n < 80; n++) {
            data(d);
            data(d);
        }
    }
}

/***********************************************************/
//This function displays a one pixel border around the Display Active Area
void One_pixel()              
{
    Write_enable();
    for (int x = 0; x < 160; x++) {
        if (x == 0 || x == 159) {
            data(0xFF);
        }
        else {
            data(0x80);
        }
    }
    for (int y = 0; y < 11; y++) {
        for (int i = 0; i < 160; i++) {
            if (i == 0 || i == 159) {
                data(0xFF);
            }
            else {
                data(0x00);
            }
        }
    }
    for (int x = 0; x < 160; x++) {
        if (x == 0 || x == 159) {
            data(0xFF);
        }
        else {
            data(0x10);
        }
    }
}

void setup() {

    setpins();      //Setting Arduino Pins

    digitalWrite(RST, LOW);
    delay(200);
    digitalWrite(RST, HIGH);
    delay(100);
    command(0x31);  //Extension Command 2
    command(0xD7);  //Disable Auto Read
    data(0x9F);
    command(0xE0);  //Enable OTP read (One-Time Programmable (OTP) ROM)
    data(0x00);
    delay(10);
    command(0xE3);  //OTP Up-Load
    delay(20);
    command(0xE1);  //OTP Control Out
    command(0x30);  //Extension Command 1
    command(0x94);  //Sleep Out
    command(0xAE);  //Display OFF
    delay(50);
    command(0x20);  //Power Control
    data(0x0B);     //VB, VR, VF All on
    delay(100);
    command(0x81);  //Set Vop = 11.6V
    data(0x08);
    data(0x03);
    command(0x31);  //Extension Command 2
    command(0x20);  //Set Gray Scale Level
    data(0x00);
    data(0x00);
    data(0x00);
    data(0x17);     //Light Gray Level Setting
    data(0x17);     //Light Gray Level Setting
    data(0x17);     //Light Gray Level Setting
    data(0x00);
    data(0x00);
    data(0x1D);     //Dark Gray Level Setting
    data(0x00);
    data(0x00);
    data(0x1D);     //Dark Gray Level Setting
    data(0x1D);     //Dark Gray Level Setting
    data(0x1D);     //Dark Gray Level Setting
    data(0x00);
    data(0x00);
    command(0x32);  //Analog Circuit Set
    data(0x00);
    data(0x01);     //Booster Efficiency = Level 1 (default)
    data(0x03);     //Bias=1/11 
    command(0x51);  //Booster Level x10 (default)
    data(0xFB);
    command(0x30);  //Extension Command 1
    command(0xF0);  //Display Mode
    data(0x10);     //4Gray Mode 0x11 / monochrome 0x10
    command(0xCA);  //Display Control
    data(0x00);     //CL Dividing Ratio Not Divide
    data(0x63);     //Duty Set 160 Duty  
    data(0x00);     //Frame Inversion
    command(0xBC);  //Data Scan Direction
    data(0x00);
    command(0xA6);  //Normal Display
    command(0x31);  //Extension Command 2
    command(0x40);  //Internal Power Supply (default)
    command(0x30);  //Extension Command 1
    command(0x77);  //Enable ICON RAM
    command(0x15);  //Column Address Setting
    data(0x00);     //SEG0 -> SEG159
    data(0x9F);
    command(0x76);  //Disable ICON RAM
    command(0x30);  //Extension Command 1
    command(0x75);  //Row Address Setting
    data(0x00);     //COM0 -> COM100
    data(0x18);
    command(0xAF);  //Display ON

    delay(200);
    fill_screen(0x00); //Clear Screen
}



void loop() {

    One_pixel();                //Pixel border displayed
    delay(1600);
    fill_screen(0x00);          //Clears screen
    delay(1000);
    ImageDisplay(NHD_Logo);     //Displays Logo image
    delay(1900);
    fill_screen(0xff);          //All pixels on
    delay(1600);
}
